"""Render the reference path as a deployable transformation module.

The rendered module defines ``transform(row)`` exactly like any other
transformation, so the pipeline can activate it in place of a failing
candidate. It embeds the incumbent code, renamed to ``_incumbent``, and the
drift events from which the backward mapping is rebuilt at import time.
"""

from __future__ import annotations

import ast
import json
from dataclasses import asdict

from src.reference.drift import DriftEvent


HEADER = '"""Reference path generated by SchemaGuard from a drift event. Do not edit."""\n'


def render_reference_module(incumbent_code: str, events: tuple[DriftEvent, ...]) -> str:
    tree = ast.parse(incumbent_code)
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == "transform":
            node.name = "_incumbent"
    incumbent = ast.unparse(tree)
    payload = json.dumps([asdict(event) for event in events])
    return (
        HEADER
        + "import json\n"
        + "from src.reference.drift import DriftEvent\n"
        + "from src.reference.mapping import derive_backward_mapping\n\n"
        + f"_EVENTS = {payload!r}\n"
        + "_MAPPING = derive_backward_mapping(tuple(\n"
        + "    DriftEvent(**{k: tuple(v) if isinstance(v, list) else v for k, v in e.items()})\n"
        + "    for e in json.loads(_EVENTS)\n"
        + "))\n\n\n"
        + incumbent
        + "\n\n\ndef transform(row):\n"
        + "    prior, _ = _MAPPING.apply(row)\n"
        + "    return _incumbent(prior)\n"
    )
